import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { parse } from 'dotenv';
const settings = parse(readFileSync('.env'));
test('Russian and Ukrainian interfaces preserve language and candidate data', async ({ page }) => {
  await page.goto('/');
  await page.getByTestId('language-switch').selectOption('ru');
  await page.getByLabel('Пароль владельца').fill('incorrect-password');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.locator('.error[role=alert]')).toContainText('Неверный пароль.');
  await page.getByLabel('Пароль владельца').fill(settings.OWNER_PASSWORD);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
  await expect(page.getByTestId('language-switch')).toHaveValue('ru');
  await page.getByRole('button', { name: 'Компании', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить компанию', exact: true }).click();
  await expect(page.getByLabel('Название компании')).toBeVisible();
  await page.getByRole('button', { name: 'Закрыть окно' }).click();
  await page.getByRole('button', { name: 'Отклики', exact: true }).click();
  const company = await page.locator('.table-link strong').first().textContent();
  await page.locator('.table-link').first().click();
  await expect(page.getByRole('heading', { name: 'История событий' })).toBeVisible();
  await expect(page.locator('.timeline')).not.toContainText('Application draft created');
  await page.getByTestId('language-switch').selectOption('uk');
  await expect(page.getByRole('heading', { name: 'Історія подій' })).toBeVisible();
  await expect(page.locator('.detail-heading')).toContainText(company!);
  await page.getByRole('button', { name: 'Джерела', exact: true }).click();
  await expect(page.getByText('Український IT-ринок').first()).toBeVisible();
  await page.getByRole('button', { name: 'Стан системи', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Діагностика інфраструктури' })).toBeVisible();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'uk');
  await page.getByRole('button', { name: 'Огляд', exact: true }).click();
  await page.screenshot({ path: 'docs/reviews/phase-1/ukrainian.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({ path: 'docs/reviews/phase-1/ukrainian-mobile.png', fullPage: true });
  await page.getByTestId('language-switch').selectOption('ru');
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
});

