const dictionaries = {
  en: new Map(messages.map(([en]) => [en, en])),
  ru: new Map(messages.map(([en, ru]) => [en, ru])),
  uk: new Map(messages.map(([en, , uk]) => [en, uk])),
};
export function translate(
  locale: Locale,
  key: string,
  values: Record<string, string | number> = {},
) {
  const text = dictionaries[locale].get(key) ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

