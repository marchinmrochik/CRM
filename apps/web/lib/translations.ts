export function statusLabel(locale: Locale, value: string) {
  return (
    statusLabels[value]?.[{ en: 0, ru: 1, uk: 2 }[locale]] ??
    value.replaceAll('_', ' ').replace(/^./, (s) => s.toUpperCase())
  );
}
export function formatDate(locale: Locale, value?: string) {
  return value
    ? new Intl.DateTimeFormat({ en: 'en-GB', ru: 'ru-RU', uk: 'uk-UA' }[locale], {
        dateStyle: 'medium',
        timeStyle: 'short',
      }).format(new Date(value))
    : '—';
}
export function eventLabel(
  locale: Locale,
  event: { type?: string; label: string; metadata?: Record<string, unknown> },
) {
  const t = (key: string, values?: Record<string, string>) => translate(locale, key, values);
  const transition = event.label.match(/^(\w+) → (\w+)$/);
  if (transition)
    return `${statusLabel(locale, transition[1])} → ${statusLabel(locale, transition[2])}`;
  if (event.label.startsWith('Next action: '))
    return t('Next action: {title}', { title: event.label.slice(13) });
  const interview = event.label.match(/^(\w+) interview scheduled$/);
  if (interview)
    return t('{type} interview scheduled', { type: statusLabel(locale, interview[1]) });
  const outcome = event.label.match(/^Interview (completed|cancelled)$/);
  if (outcome) return t('Interview {status}', { status: statusLabel(locale, outcome[1]) });
  return t(event.label);
}
